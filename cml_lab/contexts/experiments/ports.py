"""Experiments resolve other contexts through read contracts."""

from typing import Protocol


class AlgorithmCataloguePort(Protocol):
    def spec(self, algorithm_id: str) -> dict: ...


class ExperimentRepository(Protocol):
    def save(self, name: str, spec: dict, result: dict, run_id: str) -> dict: ...
    def get(self, identifier: str) -> dict: ...
    def list(self) -> list[dict]: ...
    def update(self, identifier: str, patch: dict) -> dict: ...
    def delete(self, identifier: str) -> None: ...
