/** Real analysis DTOs reach lazy plots; snapshot changes discard stale requests. */
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
const require = createRequire(import.meta.url);
let JSDOM;
try { ({ JSDOM } = require('jsdom')); }
catch { ({ JSDOM } = require(`${process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES}/jsdom`)); }
const { window } = new JSDOM('<!doctype html><head></head><body></body>', { url: 'http://localhost/' });
Object.assign(globalThis, { window, document: window.document, Node: window.Node, getComputedStyle: window.getComputedStyle.bind(window) });
const { renderAnalysis } = await import('../web/cml/analysis.js');
const fixture = JSON.parse(readFileSync(new URL('./fixtures/cml-analysis.json', import.meta.url), 'utf8'));
const clone = value => structuredClone(value);
const flush = async () => { for (let i = 0; i < 5; i++) await new Promise(resolve => setTimeout(resolve, 0)); };
const change = (node, value) => { node.value = value; node.dispatchEvent(new window.Event('change')); };

function subject({ request } = {}) {
  const container = document.createElement('div'); document.body.append(container);
  const requests = [], plots = [], purged = [], errors = [];
  globalThis.Plotly = { react: async (node, traces, layout) => plots.push({ node, traces: clone(traces), layout: clone(layout) }), purge: node => purged.push(node) };
  const api = { request: async (path, options) => {
    requests.push({ path, ...options });
    if (request) return request(path, options);
    return clone(options.body.kind === 'overview' ? fixture.overview : fixture[options.body.kind] || fixture.ecdf);
  } };
  const controller = renderAnalysis(container, { api, dataset: clone(fixture.dataset), onError: error => errors.push(error) });
  return { container, requests, plots, purged, errors, controller };
}

test('overview is the only initial request and the actual three main plots are visible', async () => {
  const state = subject(); await state.controller.ready; await flush();
  assert.equal(state.requests.length, 1); assert.equal(state.requests[0].body.kind, 'overview');
  assert.equal(state.plots.length, fixture.overview.plots.length);
  assert.deepEqual(state.plots[0].traces, fixture.overview.plots[0].traces);
  assert.match(state.container.textContent, /Дубли строк/);
  assert.equal(state.container.querySelectorAll('.cml-analysis-main .cml-analysis-card').length, 3);
  assert.deepEqual(state.errors, []); state.controller.destroy();
});

test('ECDF is generated by button with the selected column and real cumulative fractions', async () => {
  const state = subject(); await state.controller.ready;
  change(state.controller.kind, 'ecdf');
  assert.equal(state.requests.length, 1);
  state.controller.generateButton.click(); await flush();
  assert.equal(state.requests.length, 2);
  assert.equal(state.requests[1].method, 'POST');
  assert.deepEqual(state.requests[1].body.columns, ['x']);
  assert.deepEqual(state.plots.at(-1).traces, fixture.ecdf.traces);
  assert.equal(state.controller.generated.children.length, 1);
  assert.match(state.controller.generated.textContent, /11 из 12 строк/);
  state.controller.destroy();
});

test('scatter uses independent selected axes and canonical options without training requests', async () => {
  const state = subject(); await state.controller.ready;
  change(state.controller.category, 'Relations'); change(state.controller.kind, 'scatter');
  assert.deepEqual(state.controller.columnControls.map(control => control.value), ['x', 'y']);
  state.controller.optionControls.get('sample_size').value = '500';
  await state.controller.generate();
  assert.deepEqual(state.requests.at(-1).body, { dataset_id: fixture.dataset.id, kind: 'scatter', columns: ['x', 'y'], options: { sample_size: 500 } });
  assert.deepEqual(state.plots.at(-1).traces[0].x, fixture.scatter.traces[0].x);
  assert.deepEqual(state.plots.at(-1).traces[0].customdata, fixture.scatter.traces[0].customdata);
  assert.ok(state.requests.every(request => request.path === '/cml/analysis'));
  state.controller.destroy();
});

test('category filter and every form label expose Russian explanations in the new lesson', async () => {
  const state = subject(); await state.controller.ready;
  change(state.controller.category, 'Time');
  assert.deepEqual([...state.controller.kind.options].map(option => option.value), ['time_line', 'rolling_mean', 'autocorrelation']);
  change(state.controller.kind, 'rolling_mean');
  assert.ok(state.controller.optionControls.has('window'));
  for (const control of state.container.querySelectorAll('select,input')) assert.ok(state.container.querySelector(`label[for="${control.id}"]`));
  for (const help of state.container.querySelectorAll('.cml-help-button')) {
    assert.equal(new URL(help.href).searchParams.get('id'), 'dataset-analysis');
    assert.equal(help.target, '_blank');
    assert.ok(document.getElementById(help.getAttribute('aria-describedby')));
  }
  assert.match(state.controller.explanation.textContent, /будущих/);
  state.controller.destroy();
});

test('switching snapshots aborts requests and rejects a stale overview response', async () => {
  let finishOld;
  const firstId = fixture.dataset.id;
  const state = subject({ request: async (_, { body }) => body.dataset_id === firstId
    ? new Promise(resolve => { finishOld = resolve; }) : clone(fixture.overview) });
  const originalRequest = state.requests[0];
  await state.controller.setDataset({ ...fixture.dataset, id: 'new-snapshot', name: 'Новая редакция' });
  assert.equal(originalRequest.signal.aborted, true);
  finishOld({ ...fixture.overview, summary: { rows: 999 } });
  await state.controller.ready; await flush();
  assert.match(state.container.textContent, /Новая редакция/);
  assert.doesNotMatch(state.container.textContent, /999/);
  assert.equal(state.controller.dataset.id, 'new-snapshot');
  assert.deepEqual(state.errors, []); state.controller.destroy();
});

test('delete, clear and destroy purge chart state without deleting datasets', async () => {
  const state = subject(); await state.controller.ready;
  change(state.controller.kind, 'ecdf'); await state.controller.generate();
  state.controller.generated.querySelector('button').click();
  assert.equal(state.controller.generated.children.length, 0); assert.equal(state.purged.length, 1);
  await state.controller.generate(); await state.controller.generate();
  [...state.container.querySelectorAll('button')].find(node => node.textContent === 'Очистить дополнительные графики').click();
  assert.equal(state.controller.generated.children.length, 0); assert.equal(state.purged.length, 3);
  state.controller.destroy();
  assert.equal(state.container.children.length, 0); assert.equal(state.purged.length, 6);
  assert.ok(state.requests.every(request => request.method === 'POST'));
});

test('twelve chart limit removes old plots while preserving the main overview', async () => {
  const state = subject(); await state.controller.ready;
  change(state.controller.kind, 'ecdf');
  for (let index = 0; index < 13; index++) await state.controller.generate();
  assert.equal(state.controller.generated.children.length, 12);
  assert.equal(state.container.querySelectorAll('.cml-analysis-main .cml-analysis-card').length, 3);
  assert.equal(state.purged.length, 1);
  state.controller.destroy();
});

test('server rejection is readable and a corrected graph can be requested again', async () => {
  let rejected = true;
  const state = subject({ request: async (_, { body }) => {
    if (body.kind === 'overview') return clone(fixture.overview);
    if (rejected) throw new Error('Autocorrelation требует равномерные моменты.');
    return clone(fixture.ecdf);
  } });
  await state.controller.ready; change(state.controller.kind, 'ecdf');
  await state.controller.generate(); assert.match(state.controller.status.textContent, /равномерные/);
  assert.equal(state.controller.generated.children.length, 0); assert.equal(state.errors.length, 1);
  assert.equal(state.controller.generateButton.disabled, false);
  rejected = false; await state.controller.generate(); assert.equal(state.controller.generated.children.length, 1);
  state.controller.destroy();
});

test('duplicate axes and invalid ranges stop before making a graph request', async () => {
  const state = subject(); await state.controller.ready; change(state.controller.kind, 'scatter');
  state.controller.columnControls[1].value = state.controller.columnControls[0].value;
  await state.controller.generate(); assert.equal(state.requests.length, 1);
  assert.match(state.controller.status.textContent, /разные столбцы/);
  state.controller.columnControls[1].value = 'y'; state.controller.optionControls.get('sample_size').value = '9000';
  await state.controller.generate(); assert.equal(state.requests.length, 1);
  assert.match(state.controller.status.textContent, /диапазоны/);
  state.controller.destroy();
});

test('empty selection and destroyed controller cannot fetch an obsolete dataset', async () => {
  const state = subject(); await state.controller.ready;
  await state.controller.setDataset(null); assert.match(state.container.textContent, /Выберите датасет/);
  const count = state.requests.length; state.controller.destroy();
  await state.controller.setDataset(fixture.dataset); assert.equal(state.requests.length, count);
  assert.equal(state.container.children.length, 0);
});

test('a chart completing after a dataset switch cannot overwrite the new overview status', async () => {
  const state = subject(); await state.controller.ready;
  change(state.controller.kind, 'ecdf');
  let finishPlot;
  globalThis.Plotly.react = async (node, traces) => {
    if (traces[0]?.type === 'scatter') return new Promise(resolve => { finishPlot = resolve; });
  };
  const pending = state.controller.generate(); await flush();
  await state.controller.setDataset({ ...fixture.dataset, id: 'new-snapshot-2', name: 'Another dataset' });
  finishPlot(); await pending;
  assert.match(state.controller.status.textContent, /Обзор готов/);
  assert.equal(state.controller.generated.children.length, 0);
  const count = state.requests.length; await state.controller.setDataset(state.controller.dataset);
  assert.equal(state.requests.length, count);
  state.controller.destroy();
});
